"""Experiment 01b: draw an error-analysis sample from the sentence baseline's test predictions.

False alarms = sentences flagged (not "supported") with no overlapping gold span.
Misses       = sentences with a gold span that were judged "supported".
Stratified by task, fixed seed. Writes notes/error_analysis_01_samples.md for hand review.

  uv run python experiments/01b_error_sample.py
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from src.data.ragtruth import TASKS, evidence_passages, load
from src.eval.metrics import gold_for_span, predict

RESULTS = REPO_ROOT / "results" / "01_sentence_baseline"
SCORES = RESULTS / "scores_test_large_per_passage.jsonl"
SUMMARY = RESULTS / "summary_test_large_per_passage.json"
OUT = REPO_ROOT / "notes" / "error_analysis_01_samples.md"
SEED = 0
N_FALSE_ALARMS = 20  # per task
N_MISSES = 10  # per task


def main() -> None:
    params = json.loads(SUMMARY.read_text())["main"]["params"]
    examples = {e.id: e for e in load("test")}
    false_alarms = {t: [] for t in TASKS}
    misses = {t: [] for t in TASKS}
    with SCORES.open() as f:
        for line in f:
            rec = json.loads(line)
            e = examples[rec["id"]]
            for s in rec["sentences"]:
                label = predict(s["per_passage"], params["t_entail"], params["t_contradict"], params["tie_break"])
                gold = gold_for_span(e, s["start"], s["end"])
                item = (e, s, label, gold)
                if label != "supported" and not gold["hallucinated"]:
                    false_alarms[e.task_type].append(item)
                elif label == "supported" and gold["hallucinated"]:
                    misses[e.task_type].append(item)

    rng = random.Random(SEED)
    lines = [
        "# Error analysis sample: experiment 01 (sentence baseline, test)",
        "",
        (f"Generated by `experiments/01b_error_sample.py` (seed {SEED}) from "
        f"`{SCORES.name}` with t_entail={params['t_entail']}, t_contradict={params['t_contradict']}, "
        f"tie_break={params['tie_break']}. Do not edit; record judgements in "
        "`error_analysis_01.md`."),
        "",
        "Population sizes (test): "
        + ", ".join(f"{t}: {len(false_alarms[t])} false alarms / {len(misses[t])} misses" for t in TASKS),
        "",
    ]
    for kind, pool, n in (("False alarm", false_alarms, N_FALSE_ALARMS), ("Miss", misses, N_MISSES)):
        lines += [f"# {kind}s", ""]
        for task in TASKS:
            sample = rng.sample(pool[task], min(n, len(pool[task])))
            for i, (e, s, label, gold) in enumerate(sample, 1):
                passages = evidence_passages(e)
                pp = s["per_passage"]
                best_e = max(range(len(pp)), key=lambda k: pp[k][0])
                best_c = max(range(len(pp)), key=lambda k: pp[k][1])
                sent = e.response[s["start"] : s["end"]]
                tag = f"{'FA' if kind == 'False alarm' else 'M'}-{task}-{i:02d}"
                lines += [
                    f"## {tag} · response {e.id} · {e.model}",
                    "",
                    f"**Sentence:** {sent}",
                    "",
                    (f"- predicted: **{label}** · max entailment {pp[best_e][0]:.2f} (passage {best_e + 1}) · "
                    f"max contradiction {pp[best_c][1]:.2f} (passage {best_c + 1})"),
                ]
                overlapping = [sp for sp in e.spans if sp.start < s["end"] and s["start"] < sp.end]
                if overlapping:
                    for sp in overlapping:
                        note = (sp.meta or "").replace("\n", " / ")
                        lines.append(f"- gold span: \"{sp.text}\" ({sp.label_type}"
                                     f"{', implicit_true' if sp.implicit_true else ''}) — {note[:200]}")
                else:
                    lines.append(f"- gold: no span in this sentence (response has {len(e.spans)} span(s) elsewhere)")
                if e.question:
                    lines.append(f"- question: {e.question}")
                lines += ["", "<details><summary>Evidence</summary>", ""]
                for k, p in enumerate(passages):
                    mark = " ← best entailment" if k == best_e else ""
                    mark += " ← best contradiction" if k == best_c and pp[best_c][1] >= 0.5 else ""
                    lines += [f"**Passage {k + 1}** (E={pp[k][0]:.2f}, C={pp[k][1]:.2f}){mark}", "", "```", p.strip(), "```", ""]
                lines += ["</details>", "", "**Category:** ", "", "---", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")
    for t in TASKS:
        print(f"  {t}: {len(false_alarms[t])} false alarms, {len(misses[t])} misses in population")


if __name__ == "__main__":
    main()
